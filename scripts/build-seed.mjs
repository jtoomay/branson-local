// Generates supabase/seed.sql from data/categories.json + data/scraped/businesses.json.
// Usage: npm run seed:build && supabase db reset
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("..", import.meta.url);
const categories = JSON.parse(await readFile(new URL("data/categories.json", root), "utf8"));
const businesses = JSON.parse(await readFile(new URL("data/scraped/businesses.json", root), "utf8"));

const q = (v) =>
  v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`;
const b = (v) => (v ? "true" : "false");

const lines = [
  "-- AUTO-GENERATED by scripts/build-seed.mjs — do not edit by hand.",
  "begin;",
  "",
  "-- Categories",
];

for (const [i, c] of categories.entries()) {
  lines.push(
    `insert into public.categories (slug, name, headline, description, seo_title, seo_description, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.headline)}, ${q(c.description)}, ${q(c.seo_title)}, ${q(c.seo_description)}, ${i}) on conflict (slug) do nothing;`,
  );
}

lines.push("", "-- Businesses");
const known = new Set(categories.map((c) => c.slug));
const seen = new Set();
let order = 0;
for (const biz of businesses) {
  if (seen.has(biz.slug)) continue;
  seen.add(biz.slug);
  const logo = biz.image_url ?? null;
  lines.push(
    `insert into public.businesses (slug, name, tagline, description, address, city, state, zip, phone, email, website, facebook, instagram, maps_url, logo_url, source_image_url, extra_links, featured, is_published, sort_order) values (${[
      q(biz.slug), q(biz.name), q(biz.tagline), q(biz.description), q(biz.address), q(biz.city ?? "Branson"),
      q(biz.state ?? "MO"), q(biz.zip), q(biz.phone), q(biz.email), q(biz.website), q(biz.facebook),
      q(biz.instagram), q(biz.maps_url), q(logo), q(biz.source_image_url),
      `${q(JSON.stringify(biz.extra_links ?? []))}::jsonb`, b(biz.featured), "true", order++,
    ].join(", ")}) on conflict (slug) do nothing;`,
  );
  for (const cat of biz.categories ?? []) {
    if (!known.has(cat)) {
      console.warn(`! ${biz.slug}: unknown category "${cat}" — skipped`);
      continue;
    }
    lines.push(
      `insert into public.business_categories (business_id, category_id) select b.id, c.id from public.businesses b, public.categories c where b.slug = ${q(biz.slug)} and c.slug = ${q(cat)} on conflict do nothing;`,
    );
  }
}

lines.push("", "commit;", "");
await writeFile(new URL("supabase/seed.sql", root), lines.join("\n"));
console.log(`✔ seed.sql written: ${categories.length} categories, ${seen.size} businesses`);
